from __future__ import annotations

import sys
import argparse
import json
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from analyzers.phase1_pipeline import Phase1Pipeline
from phase3.dataset import GroundTruthDataset
from phase3.evaluator import evaluate
from phase3.report import save_result
from phase3.runner import run_phase1_benchmark
from phase3.matcher import MatchConfig


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the Phase-1 baseline over a Juliet manifest and evaluate it.")
    parser.add_argument("manifest", help="Juliet manifest JSON generated by generate_juliet_manifest.py")
    parser.add_argument("--out", default="results/juliet_phase1.json")
    parser.add_argument("--skip-missing", action="store_true")
    parser.add_argument("--line-tolerance", type=int, default=5)
    parser.add_argument("--no-cwe-match", action="store_true")
    parser.add_argument("--no-clang", action="store_true")
    args = parser.parse_args()

    dataset = GroundTruthDataset.from_json(args.manifest)
    pipeline = Phase1Pipeline()
    start = time.perf_counter()

    predictions = []
    reports = []
    for sample in dataset:
        path = dataset.resolve_file(sample)
        if not path.exists():
            if args.skip_missing:
                reports.append({"sample_id": sample.sample_id, "skipped": True, "reason": "missing file", "file": str(path)})
                continue
            raise FileNotFoundError(path)
        report = pipeline.analyze_file(path, run_clang=not args.no_clang)
        reports.append({"sample_id": sample.sample_id, "report": report})
        from phase3.extract_predictions import predictions_from_phase1
        predictions.extend(predictions_from_phase1(report, sample.sample_id))

    elapsed = time.perf_counter() - start
    result = evaluate(
        "juliet_phase1_static",
        predictions,
        list(dataset),
        match_config=MatchConfig(
            line_tolerance=args.line_tolerance,
            require_cwe_when_available=not args.no_cwe_match,
        ),
    )
    result.metadata.update({
        "dataset": "Juliet C/C++ 1.3",
        "manifest": str(Path(args.manifest).resolve()),
        "elapsed_seconds": elapsed,
        "samples_processed": len(reports) - sum(1 for r in reports if r.get("skipped")),
        "samples_skipped": sum(1 for r in reports if r.get("skipped")),
        "reports": reports,
    })
    save_result(result, args.out)

    print(json.dumps({
        "dataset": "Juliet C/C++ 1.3",
        "metrics": result.metrics.to_dict(),
        "per_cwe": {k: v.to_dict() for k, v in result.per_cwe.items()},
        "elapsed_seconds": elapsed,
    }, indent=2))
    print(f"Result written to {Path(args.out).resolve()}")


if __name__ == "__main__":
    main()
